// Renders the brand PNGs (app icon, social card) from the brand SVG/HTML in Chromium and writes:
//   assets/brand/{mark.svg,icon-512.png,icon-180.png,og.png}  and  src/site/assets.gen.ts (base64 for the relay).
// Run after changing src/site/brand.ts:  node scripts/build-brand-assets.mjs
import { execSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { writeFileSync, readFileSync } from 'node:fs';

const root = new URL('..', import.meta.url).pathname;
const { markSvg, BRAND } = await import(root + 'src/site/brand.ts');
const { chromium } = createRequire(import.meta.url)(execSync('npm root -g').toString().trim() + '/playwright');

writeFileSync(root + 'assets/brand/mark.svg', markSvg(512) + '\n');
writeFileSync(root + 'assets/brand/mark-flat.svg', markSvg(512, { tile: false }) + '\n');

const font = "'Inter Display',Inter,-apple-system,'Segoe UI',Roboto,Arial,sans-serif";
const og = `<!doctype html><html><body style="margin:0;width:1200px;height:630px;background:${BRAND.ink};color:${BRAND.paper};font-family:${font};overflow:hidden;position:relative">
<div style="position:absolute;right:-120px;top:-60px;width:620px;height:620px;border-radius:50%;background:radial-gradient(circle,rgba(255,90,31,.28),transparent 65%)"></div>
<div style="position:absolute;left:84px;top:72px;display:flex;align-items:center;gap:18px;font-weight:800;font-size:44px;letter-spacing:-1.5px">${markSvg(64).replace('fill="#121314"', 'fill="#1E2022"')}baton</div>
<div style="position:absolute;left:84px;top:190px;width:760px;font-weight:800;font-size:86px;line-height:1.02;letter-spacing:-3px">Move any AI chat to <span style="color:${BRAND.signal}">any other AI.</span></div>
<div style="position:absolute;left:84px;bottom:76px;display:flex;gap:14px;font-size:26px;font-weight:700">
${[['ChatGPT', '#10A37F'], ['Claude', '#D97757'], ['Gemini', '#4F7DF3']].map(([n, c]) => `<span style="display:flex;align-items:center;gap:10px;padding:12px 20px;border-radius:999px;background:#1E2022"><i style="width:14px;height:14px;border-radius:50%;background:${c}"></i>${n}</span>`).join('')}
<span style="display:flex;align-items:center;padding:12px 4px;color:#9C988F">Prompts · answers · files · what's missing</span></div>
<div style="position:absolute;right:70px;top:230px;transform:rotate(-38deg);width:240px;height:88px;border-radius:999px;background:${BRAND.signal};box-shadow:0 30px 80px -20px rgba(255,90,31,.7)"></div>
</body></html>`;

const b = await chromium.launch({ channel: 'chromium' });
const p = await b.newPage();
const shot = async (html, w, h, file) => {
  await p.setViewportSize({ width: w, height: h });
  await p.setContent(html);
  const buf = await p.screenshot({ type: 'png', omitBackground: false });
  writeFileSync(root + 'assets/brand/' + file, buf);
  return buf;
};
const icon = (s) => `<!doctype html><html><body style="margin:0;background:${BRAND.ink}">${markSvg(s).replace('rx="9"', 'rx="0"')}</body></html>`;
const icon180 = await shot(icon(180), 180, 180, 'icon-180.png');
await shot(icon(512), 512, 512, 'icon-512.png');
const ogBuf = await shot(og, 1200, 630, 'og.png');
await b.close();

writeFileSync(root + 'src/site/assets.gen.ts', `// Generated by scripts/build-brand-assets.mjs. Do not edit.\nexport const ICON_PNG_B64 = '${icon180.toString('base64')}';\nexport const OG_PNG_B64 = '${ogBuf.toString('base64')}';\n`);
console.log(`icon ${icon180.length} B · og ${ogBuf.length} B`);
